    // 23:45 IST stays on its business date and is not shifted by the server timezone.
    expect(visitorRows[2]?.slice(1, 6)).toEqual(["2026-09-08", "Mr. Rajesh Kumar Venkataraman", expect.any(String), "11:45 PM", "11:59 PM"]);
    expect(visitorRows.slice(3).every((row) => row[0] === "Human Resources")).toBe(true);
