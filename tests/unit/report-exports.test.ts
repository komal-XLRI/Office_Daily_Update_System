function pdfPageCount(pdf: Buffer): number {
  return (pdf.toString("latin1").match(/\/Type\s*\/Page(?![a-zA-Z])/g) ?? []).length;
}

describe("renderReportPdf", () => {
  it("renders a multi-page A4 PDF for a realistic all-offices report", async () => {
    const data = buildSampleReport();
    const snapshot = JSON.stringify(data);
    const pdf = await renderReportPdf(data);

    expect(Buffer.isBuffer(pdf)).toBe(true);
    expect(pdf.subarray(0, 5).toString("latin1")).toBe("%PDF-");
    expect(pdf.subarray(-7).toString("latin1")).toContain("%%EOF");
    expect(pdf.length).toBeGreaterThan(10_000);
    expect(pdfPageCount(pdf)).toBeGreaterThanOrEqual(2);
    expect(pdf.toString("latin1")).toMatch(/\/MediaBox\s*\[\s*0 0 595\.2?8?\d* 841\.8\d*\s*\]/);
    // Rendering does not mutate the report.
    expect(JSON.stringify(data)).toBe(snapshot);

    // Attachment links are real URI annotations for http(s) files only (spec §19 "links where appropriate").
    const raw = pdf.toString("latin1");
    expect(raw).toMatch(/\/URI\s*\(https:\/\/res\.cloudinary\.com\/odums-demo\/raw\/upload\/[^)]*minutes-07-sep\.pdf\)/);
    expect(raw).not.toContain("javascript:");
  }, 60_000);

  it("renders a single-page PDF for an empty single-office daily report", async () => {
    const pdf = await renderReportPdf(buildEmptyDailyReport());
    expect(pdf.subarray(0, 5).toString("latin1")).toBe("%PDF-");
    expect(pdf.length).toBeGreaterThan(1_500);
    expect(pdfPageCount(pdf)).toBe(1);
  }, 60_000);
});

describe("reportFileName", () => {
  const base: ReportMeta = buildSampleReport().meta;
  const meta = (overrides: Partial<ReportMeta>): ReportMeta => ({ ...base, ...overrides });

  it.each([
    ["all offices, weekly range", meta({}), "pdf", "report-weekly-all-offices-2026-09-07-to-2026-09-13.pdf"],
    [
      "single office daily",
      meta({ type: "daily", officeId: "64f1", officeLabel: "Dean (Admin) & HR", from: "2026-09-08", to: "2026-09-08" }),
      "csv",
      "report-daily-dean-admin-hr-2026-09-08.csv",
    ],
    [
      "monthly uses the month only",
      meta({ type: "monthly", officeId: "64f1", officeLabel: "Office A", from: "2026-09-01", to: "2026-09-30" }),
      "xlsx",
      "report-monthly-office-a-2026-09.xlsx",
    ],
    [
      "custom single day",
      meta({ type: "custom", officeId: null, from: "2026-09-08", to: "2026-09-08" }),
      "pdf",
      "report-custom-all-offices-2026-09-08.pdf",
    ],
    [
      "accents are transliterated, quotes and paths dropped",
      meta({ officeId: "64f1", officeLabel: 'Café "Ünïcode" / ../../etc 日本' }),
      "csv",
      "report-weekly-cafe-unicode-etc-2026-09-07-to-2026-09-13.csv",
    ],
    ["non-Latin office names fall back to office", meta({ officeId: "64f1", officeLabel: "प्रशासन 日本" }), "pdf", "report-weekly-office-2026-09-07-to-2026-09-13.pdf"],
    ["extension is normalised", meta({}), ".PDF", "report-weekly-all-offices-2026-09-07-to-2026-09-13.pdf"],
    ["unsafe extension characters are removed", meta({}), 'x"/../y', "report-weekly-all-offices-2026-09-07-to-2026-09-13.xy"],
    ["empty extension becomes bin", meta({}), "", "report-weekly-all-offices-2026-09-07-to-2026-09-13.bin"],
  ])("%s", (_label, input, extension, expected) => {
    expect(reportFileName(input, extension)).toBe(expected);
  });

  it("caps long office slugs at 60 characters without a trailing hyphen", () => {
    const name = reportFileName(
      meta({ type: "daily", officeId: "64f1", officeLabel: `${"Department of ".repeat(10)}Studies`, from: "2026-09-08", to: "2026-09-08" }),
      "pdf",
    );
    const slug = name.replace(/^report-daily-/, "").replace(/-2026-09-08\.pdf$/, "");
    expect(slug.length).toBeLessThanOrEqual(60);
    expect(slug).not.toMatch(/-$/);
    expect(slug.startsWith("department-of-department-of")).toBe(true);
  });

  it("always produces a header-safe ASCII name", () => {
    const hostile = ['a"; filename=evil.exe', "..\\..\\x", "\r\nSet-Cookie: x=1", "😀", "Office‮gpj.exe"];
    for (const officeLabel of hostile) {
      const name = reportFileName(meta({ officeId: "64f1", officeLabel }), "pdf");
      expect(name).toMatch(/^report-weekly-[a-z0-9-]+-2026-09-07-to-2026-09-13\.pdf$/);
    }
  });
});
