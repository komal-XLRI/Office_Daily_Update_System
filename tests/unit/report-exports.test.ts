type LoadedCell = ExcelJS.Cell;

function cellText(cell: LoadedCell): string | null {
  const value = cell.value;
  if (typeof value === "string") return value;
  if (value && typeof value === "object" && "text" in value && typeof value.text === "string") return value.text;
  if (value && typeof value === "object" && "richText" in value) return value.richText.map((part) => part.text).join("");
  return null;
}

function rowTexts(sheet: ExcelJS.Worksheet, rowNumber: number): (string | number | null)[] {
  const row = sheet.getRow(rowNumber);
  const values: (string | number | null)[] = [];
  for (let column = 1; column <= row.cellCount; column += 1) {
    const cell = row.getCell(column);
    values.push(typeof cell.value === "number" ? cell.value : cellText(cell));
  }
  return values;
}

async function loadWorkbook(data: ReportData): Promise<ExcelJS.Workbook> {
  const buffer = await reportToXlsx(data);
  expect(Buffer.isBuffer(buffer)).toBe(true);
  expect(buffer.subarray(0, 2).toString("latin1")).toBe("PK");
  const workbook = new ExcelJS.Workbook();
  await workbook.xlsx.load(buffer as unknown as ExcelJS.Buffer);
  return workbook;
}

function sheet(workbook: ExcelJS.Workbook, name: string): ExcelJS.Worksheet {
  const found = workbook.getWorksheet(name);
  if (!found) throw new Error(`Missing worksheet "${name}"`);
  return found;
}

